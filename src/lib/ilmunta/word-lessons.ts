/**
 * 드릴에서 이 낱말을 쓰기 시작하는 일문따 과. 0이면 처음부터.
 * 일무따(1분기)를 끝낸 뒤 일문따(2분기)를 하므로, 일무따에 나온 낱말은 처음부터 안다고 본다.
 * 교재에 안 나오는 기본 낱말도 처음부터 쓴다.
 */
export function drillLessonOf(dict: string): number {
  const w = WORD_LESSONS[dict];
  if (!w || w.ilmuta != null) return 0;
  return w.ilmunta ?? 0;
}
