import type { KoStem } from "./korean";

/**
 * 문장 빈칸 문제의 낱말을 뜻 범주(장면)로 묶는다. 세션이 직접 지은 짧은 구절이다(교재 문장을 옮기지 않음).
 * 문장 틀은 장면 하나를 받아, 그 장면에 든 낱말만 빈칸에 넣는다. 그래서 「窓を食べる」 같은 조합이 나오지 않는다.
 *
 * - `dict`는 verbs.ts·words.ts에 있는 낱말이어야 한다(시험이 확인한다).
 * - `pre`·`post`는 빈칸 앞뒤에 붙는 일본어(`[漢字|かな]` 표기), `koPre`·`koPost`는 그 한국어.
 * - `ko`는 한국어 서술어의 줄기와 아/어 꼴(korean.ts).
 */
export interface SceneWord {
  dict: string;
  pre: string;
  koPre: string;
  ko: KoStem;
  post?: string;
  koPost?: string;
  /** 한국어로는 동사인 형용사(好き → 좋아하다, 上手 → 잘하다) */
  koVerb?: boolean;
  /** 형용사의 느낌: 좋은 쪽이면 「～くて、うれしい」, 나쁜 쪽이면 「～くて、大変」에 들어간다 */
  tone?: "good" | "bad";
}

export type SceneId =
  // 동사
  | "daily" // 날마다 하는 일(毎日·昨日와 어울림)
  | "request" // ～てください로 부탁할 일
  | "beforeOut" // 나가기 전에 하는 일
  | "whenDone" // ～たら 뒤에 연락할 일
  | "practice" // 날마다 하면 느는 일
  | "canDo" // 할 수 있게 된 일
  | "annoyed" // 남이 해서 싫은 일(피해 수동)
  | "momMakes" // 엄마가 시키는 일
  | "teacherMakes" // 선생님이 시키는 일
  | "together" // 같이 하자고 할 일
  | "hurry" // 빨리 하라고 할 일
  | "forbidden" // 위험해서 하지 말라고 할 일
  // 형용사·명사
  | "quality" // 사물·사람의 성질
  | "manner" // 어떻게 해 달라는 부사형
  | "job"; // 직업 명사

type Row = [
  dict: string,
  pre: string,
  koPre: string,
  ko: KoStem,
  more?: Partial<SceneWord>,
];

const rows = (list: Row[]): SceneWord[] =>
  list.map(([dict, pre, koPre, ko, more]) => ({
    dict,
    pre,
    koPre,
    ko,
    ...more,
  }));

