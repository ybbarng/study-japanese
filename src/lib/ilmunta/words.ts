function rows(kind: AdjKind, list: Row[]): Adjective[] {
  return list.map(([dict, reading, ko, alive]) => ({
    dict,
    reading,
    ko,
    kind,
    lesson: drillLessonOf(dict),
    ...(alive ? { alive } : {}),
  }));
}

export const ADJECTIVES: readonly Adjective[] = [
  ...rows("i", I_ADJ),
  ...rows("na", NA_ADJ),
  ...rows("noun", NOUNS),
];

export function wordsOf(kind: AdjKind): Adjective[] {
  return ADJECTIVES.filter((a) => a.kind === kind);
}
