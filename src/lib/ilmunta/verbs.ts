function rows(group: VerbGroup, list: Row[]): Verb[] {
  return list.map(([dict, reading, ko, basicOnly]) => ({
    dict,
    reading,
    ko,
    group,
    lesson: drillLessonOf(dict),
    ...(basicOnly ? { basicOnly } : {}),
  }));
}

export const VERBS: readonly Verb[] = [
  ...rows("godan", GODAN),
  ...rows("ichidan", ICHIDAN),
  ...rows("suru", SURU),
  ...rows("kuru", KURU),
];

export function verbsOf(group: VerbGroup): Verb[] {
  return VERBS.filter((v) => v.group === group);
}

export const VERB_BY_DICT: ReadonlyMap<string, Verb> = new Map(
  VERBS.map((v) => [v.dict, v]),
);
