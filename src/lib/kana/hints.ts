export function hintFor(id: CardId): string {
  const { script, soundId } = parseCardId(id);
  const sound = getSound(soundId);
  const table = script === "hira" ? HIRA : KATA;
  const ch = (x: { hira?: string; kata?: string }) =>
    (script === "hira" ? x.hira : x.kata) ?? "";

  switch (sound.kind) {
    case "basic":
      return table[soundId] ?? "";
    case "dakuten": {
      const base = getSound(DAKU_TO_BASE[soundId]);
      const extra =
        soundId === "di" || soundId === "du"
          ? " じ·ず와 소리가 같아 낱말 몇 개에만 나온다"
          : "";
      return `${ch(base)}에 점 두 개(탁점)를 찍으면 소리가 탁해진다: ${DAKU_BASE[sound.row]} → ${sound.row}.${extra}`;
    }
    case "handakuten": {
      const base = getSound(DAKU_TO_BASE[soundId]);
      return `${ch(base)}에 작은 동그라미(반탁점)를 달면 ㅍ 소리가 된다`;
    }
    case "yoon": {
      const full = ch(sound);
      return `${full[0]} 뒤에 작은 ${full[1]}를 붙여 한 박에 '${sound.ko}'로 읽는다`;
    }
    case "extended": {
      const full = ch(sound);
      return `${full[0]} 뒤에 작은 ${full[1]}를 붙여 외래어 소리 '${sound.romaji}'를 낸다`;
    }
  }
}
